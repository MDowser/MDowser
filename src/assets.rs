/// App icon (256x256 PNG) for the OS window, taskbar and alt-tab menu.
pub const APP_ICON_256: &[u8] = include_bytes!("../assets/icons/icon-256.png");

/// Third-party notices (`THIRD_PARTY_NOTICES.md`): the exact file shipped in
/// every release archive, embedded so the internal licenses page
/// (`about:licenses`) renders it offline from the same text the running
/// binary was distributed with. Parsed once per process by
/// [`crate::licenses::document`].
pub const THIRD_PARTY_NOTICES: &str = include_str!("../THIRD_PARTY_NOTICES.md");

/// Decodes [`APP_ICON_256`] into the `IconData` eframe wants.
///
/// Returns `None` when the embedded PNG cannot be decoded: the OS then keeps
/// its default icon instead of failing the launch. Decoding runs once, at
/// startup, on an image already validated by the generator; the decoded
/// pixels are cached for later callers (macOS decodes the same icon for
/// AppKit's About panel), so the PNG is decoded once per process.
pub fn window_icon() -> Option<eframe::egui::IconData> {
    static CACHE: std::sync::OnceLock<Option<eframe::egui::IconData>> = std::sync::OnceLock::new();
    CACHE
        .get_or_init(|| {
            let img = image::load_from_memory(APP_ICON_256).ok()?.into_rgba8();
            let (width, height) = img.dimensions();
            Some(eframe::egui::IconData {
                rgba: img.into_raw(),
                width,
                height,
            })
        })
        .clone()
}

#[cfg(test)]
mod tests {
    /// The embedded icon must decode and stay square, or `with_icon` gets
    /// garbage (or nothing) on every platform.
    #[test]
    fn window_icon_decodes_square() {
        let icon = super::window_icon().expect("embedded icon decodes");
        assert_eq!(icon.width, icon.height);
        assert_eq!(icon.width, 256);
        assert_eq!(icon.rgba.len(), (icon.width * icon.height * 4) as usize);
    }

    /// The compressed fonts must decompress to the exact build-recorded
    /// length with a valid sfnt header, and the `OnceLock` must hand every
    /// caller the SAME buffer (one copy in memory, shared by epaint, the
    /// SVG fontdb and `media::emoji`).
    #[test]
    fn compressed_fonts_decompress_once_to_the_recorded_size() {
        let cjk = super::noto_sans_cjk();
        assert_eq!(cjk.len(), super::NOTO_SANS_CJK_UNCOMPRESSED);
        assert_eq!(&cjk[..4], b"ttcf", "CJK must be a TrueType collection");
        assert!(
            std::ptr::eq(cjk, super::noto_sans_cjk()),
            "the CJK buffer is decompressed once and shared"
        );

        let emoji = super::noto_color_emoji();
        assert_eq!(emoji.len(), super::NOTO_COLOR_EMOJI_UNCOMPRESSED);
        assert_eq!(
            &emoji[..4],
            b"\x00\x01\x00\x00",
            "emoji must be a TrueType font"
        );
        assert!(
            std::ptr::eq(emoji, super::noto_color_emoji()),
            "the emoji buffer is decompressed once and shared"
        );
    }
}
