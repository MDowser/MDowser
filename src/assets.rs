//! `assets`: binary assets embedded in the executable.
//!
//! The OFL-1.1 Noto families below make up the text stack registered for
//! UI text (`ui::theme::apply`) and statically rasterized SVG text
//! (`media::decode`). The primaries are bundled Noto Sans faces —
//! [`NOTO_SANS`] for proportional text and the Noto Sans Mono CJK cut
//! (face 5 of [`noto_sans_cjk`]) for code — and the rest are glyph
//! fallbacks for code points they cannot draw. Nothing else is registered
//! anywhere: epaint's bundled default faces never reach the screen.
//!
//! - `NOTO_SANS`: Noto Sans (variable `wdth`/`wght`, default Regular).
//!   The app's proportional typeface (chrome, menus, documents) and the
//!   source of the bold face pinned to `wght = 700`
//!   (`ui::theme::strong_family`). It is also the SVG font database's
//!   default and generic `serif`/`sans-serif`/`cursive`/`fantasy` family.
//! - `NOTO_EMOJI`: Noto Emoji (monochrome, variable, default Regular).
//!   epaint already bundles an older Noto Emoji subset that misses recent
//!   code points (they render as tofu boxes); this complete face fixes that.
//! - `noto_sans_cjk()`: Noto Sans CJK, the full Chinese/Japanese/Korean
//!   typeface (kana, Hangul, Bopomofo, CJK Unified Ideographs + Ext A,
//!   plus its own Latin/symbols). A `.ttc` collection: faces 0-4 are
//!   proportional (JP, KR, SC, TC, HK) and 5-9 the matching mono faces;
//!   the UI registers the JP proportional face as a CJK fallback and the
//!   JP mono face as the MONOSPACE PRIMARY (code stays truly monospaced),
//!   and the SVG fontdb loads every face, so
//!   `font-family="Noto Sans CJK SC"` resolves too.
//!   It is the largest face (~19 MB raw): real CJK coverage costs that
//!   much. It ships Brotli-compressed (`build_support/gen_fonts.rs`) and is
//!   decompressed ONCE on first use into a process-lifetime buffer that
//!   epaint, the SVG fontdb and the tests all borrow.
//! - `noto_color_emoji()`: Noto Color Emoji (COLRv1 + SVG-in-OpenType, no
//!   usable outlines). epaint cannot paint it (its text stack rasterizes
//!   monochrome outlines only), so it is NOT registered in the fallback
//!   chains nor in the SVG fontdb: `media::emoji` shapes it with harfrust
//!   and rasterizes its embedded SVG documents into inline color textures.
//!   Ships Brotli-compressed and is decompressed LAZILY, on the first color
//!   emoji a session renders: pages without emoji never allocate it.
//! - `SCRIPT_FONTS`: one Noto Sans face per major non-CJK writing system
//!   (Arabic, Hebrew, Devanagari, Bengali, Gurmukhi, Gujarati, Odia, Tamil,
//!   Telugu, Kannada, Malayalam, Sinhala, Thai, Lao, Khmer, Myanmar,
//!   Ethiopic, Armenian, Georgian, Thaana, N'Ko, Cherokee, Canadian
//!   Aboriginal and Noto Sans Symbols 2). Harfrust applies the complex
//!   shaping (Indic reordering, Arabic joining, ...) and RTL display order
//!   comes from `viewer::bidi`.
//!
//! All faces are parsed by pure Rust code (epaint rasterizes with
//! fontations and shapes with harfrust; SVG text goes through usvg's
//! fontdb). epaint lays glyphs left-to-right and applies no bidi of its
//! own, so the viewer reorders RTL runs before layout (`viewer::bidi`);
//! mixed-direction inline elements (links, code) remain approximate.
//! - `APP_ICON_256`: the app icon, shown in the window/taskbar on Windows
//!   and Linux (`main` hands it to `ViewportBuilder::with_icon`). macOS
//!   ignores the runtime icon and uses `Contents/Resources/icon.icns` from
//!   the `.app` bundle (see `scripts/build-dist.sh`); Windows executables
//!   also carry `assets/icons/icon.ico` as a PE resource (`build.rs`).
//!   The raster ladder is generated from `assets/icon.svg` by `build.rs`
//!   (`build_support/gen_icons.rs`) whenever the committed outputs are
//!   missing or outdated; `make icons` forces a regeneration.
//! - License and provenance: [`THIRD_PARTY_NOTICES.md`](../../THIRD_PARTY_NOTICES.md).

/// Noto Emoji variable font (`wght` axis, default Regular instance).
pub const NOTO_EMOJI: &[u8] = include_bytes!("../assets/fonts/NotoEmoji-Variable.ttf");

/// Noto Sans variable font (`wdth`/`wght` axes, default Regular instance):
/// the app's proportional primary face (UI chrome, menus, documents and
/// SVG text), with the same bytes re-registered pinned to `wght = 700` for
/// the bold family.
pub const NOTO_SANS: &[u8] = include_bytes!("../assets/fonts/NotoSans-Variable.ttf");

// Uncompressed lengths of the compressed fonts, generated by the build
// (`build_support/gen_fonts.rs`): the runtime preallocates exactly.
include!(concat!(env!("OUT_DIR"), "/font_meta.rs"));

/// Noto Sans CJK (Regular), TTC collection: faces 0-4 proportional
/// (JP, KR, SC, TC, HK), 5-9 mono (JP, KR, SC, TC, HK).
///
/// Brotli-compressed in the binary; the ~19 MB face is decompressed once,
/// on first use, into ONE process-lifetime buffer shared by every consumer
/// (epaint borrows it through `FontData`, the SVG fontdb wraps the same
/// slice in an `Arc`, the tests read it directly).
pub fn noto_sans_cjk() -> &'static [u8] {
    static CACHE: std::sync::OnceLock<&'static [u8]> = std::sync::OnceLock::new();
    CACHE.get_or_init(|| {
        decompress(
            include_bytes!(concat!(env!("OUT_DIR"), "/NotoSansCJK-Regular.ttc.br")),
            NOTO_SANS_CJK_UNCOMPRESSED,
            "Noto Sans CJK",
        )
    })
}

/// Noto Color Emoji (COLRv1 + SVG-in-OpenType): color emoji source for
/// `media::emoji`, never registered in the text fallback chains.
///
/// Brotli-compressed in the binary; decompressed once on the background
/// `media::emoji::prewarm` thread `App::new` spawns (this accessor itself
/// is lazy), so the face is ready before the first emoji or chrome glyph
/// needs it and no frame pays the ~24 MB decompression.
pub fn noto_color_emoji() -> &'static [u8] {
    static CACHE: std::sync::OnceLock<&'static [u8]> = std::sync::OnceLock::new();
    CACHE.get_or_init(|| {
        decompress(
            include_bytes!(concat!(env!("OUT_DIR"), "/NotoColorEmoji-Regular.ttf.br")),
            NOTO_COLOR_EMOJI_UNCOMPRESSED,
            "Noto Color Emoji",
        )
    })
}

/// Decompresses one embedded font blob once and leaks it for the process:
/// the fonts live for the whole session anyway, and a leaked slice lets
/// epaint, the SVG fontdb and `media::emoji` all borrow the SAME bytes
/// (exactly one copy in memory). `expected` comes from the build-generated
/// `font_meta.rs`, so the allocation is exact and no `Vec` growth doubling
/// ever doubles the transient peak.
///
/// The blob is round-trip validated by `build_support/gen_fonts.rs` before
/// the build can succeed, so a failure here means the binary itself was
/// modified after linking. It panics with a clear message instead of
/// handing epaint an empty slice (which would panic deeper with a worse
/// one); a corrupted binary is not a recoverable state.
#[cold]
fn corrupt_font(name: &str, detail: &str) -> ! {
    panic!("embedded font {name} is corrupt: {detail}")
}

fn decompress(blob: &'static [u8], expected: usize, name: &str) -> &'static [u8] {
    use std::io::Read as _;
    let mut out = Vec::with_capacity(expected);
    // Cap the decompressor one byte past the expected size: a corrupted
    // binary must not be able to grow `out` without bound before the
    // post-decompression length check runs.
    let read = brotli::Decompressor::new(blob, 16 * 1024)
        .take(expected as u64 + 1)
        .read_to_end(&mut out);
    match read {
        Ok(n) if n == expected => Box::leak(out.into_boxed_slice()),
        Ok(n) => corrupt_font(name, &format!("{n} bytes, expected {expected}")),
        Err(e) => corrupt_font(name, &e.to_string()),
    }
}

